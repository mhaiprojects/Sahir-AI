#!/usr/bin/env python3
"""Leave-one-out calibration for router Tier 1 (nomic embeddings + margin threshold)."""

from __future__ import annotations

import json
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from agent.config import AgentConfig
from agent.llm import OllamaEmbedder
from agent.router_t1 import (
    RouterExample,
    RouterTier1Index,
    HOLDOUT_PATH,
    load_holdout_examples,
    load_static_examples,
)
from config import Settings


def _loo_predict(
    index: RouterTier1Index,
    embedder: OllamaEmbedder,
    examples: list[RouterExample],
) -> list[tuple[str, str, str, float]]:
    """Returns list of (text, gold, pred, margin)."""
    rows: list[tuple[str, str, str, float]] = []
    for i, ex in enumerate(examples):
        subset = examples[:i] + examples[i + 1 :]
        tmp = RouterTier1Index()
        tmp._static = []
        texts = [e.text for e in subset]
        vectors = embedder.embed_documents(texts)
        import numpy as np

        tmp._static = [
            type("IE", (), {"example": subset[j], "vector": np.array(vectors[j], dtype=np.float32)})()
            for j in range(len(subset))
        ]
        hit, _ = tmp.classify(ex.text, embedder, chats=[])
        if hit is None:
            rows.append((ex.text, ex.label, "C", 0.0))
            continue
        pred = ex.label if hit.margin >= 0 else hit.label  # raw best label
        pred = hit.label
        rows.append((ex.text, ex.label, pred, hit.margin))
    return rows


def _false_sd_rate(rows: list[tuple[str, str, str, float]], margin: float) -> tuple[float, int, int]:
    """Rate of gold C classified as S or D when acting at margin threshold."""
    wrong = 0
    gold_c = 0
    for _text, gold, pred, m in rows:
        if gold != "C":
            continue
        gold_c += 1
        if m >= margin and pred in {"S", "D"}:
            wrong += 1
    return (wrong / gold_c if gold_c else 0.0, wrong, gold_c)


def _accuracy(rows: list[tuple[str, str, str, float]], margin: float) -> float:
    ok = 0
    for _t, gold, pred, m in rows:
        effective = pred if m >= margin else "C"
        if gold == effective:
            ok += 1
        elif gold in {"S", "D"} and m >= margin and pred == gold:
            ok += 1
    return ok / len(rows) if rows else 0.0


def main() -> int:
    settings = Settings.from_env()
    cfg = AgentConfig.from_env()
    embedder = OllamaEmbedder(settings.ollama_host, cfg.embed_model)
    static = load_static_examples()
    holdout = load_holdout_examples()

    index = RouterTier1Index()
    print("Warming full static index…")
    index.ensure_static(embedder)

    latencies: list[float] = []
    probes = [
        "summarise everything",
        "make the button blue",
        "stop speaking",
        "add tests for auth",
        "what chats do we have",
    ]
    for _ in range(5):
        for phrase in probes:
            t0 = time.perf_counter()
            index.classify(phrase, embedder, chats=[])
            latencies.append((time.perf_counter() - t0) * 1000)

    print(f"Running LOO on {len(static)} static examples…")
    t0 = time.perf_counter()
    loo_rows = _loo_predict(index, embedder, static)
    loo_sec = time.perf_counter() - t0

    holdout_rows: list[tuple[str, str, str, float]] = []
    for text, gold in holdout:
        hit, _ = index.classify(text, embedder, chats=[])
        holdout_rows.append((text, gold, hit.label if hit else "C", hit.margin if hit else 0.0))

    all_rows = loo_rows + holdout_rows
    margins = [m for *_, m in all_rows]
    best_margin = 0.02
    best_acc = 0.0
    for trial in [x / 200 for x in range(1, 80)]:
        rate, _w, _n = _false_sd_rate(all_rows, trial)
        if rate > 0.03:
            continue
        acc = _accuracy(all_rows, trial)
        if acc >= best_acc:
            best_acc = acc
            best_margin = trial

    rate, wrong, gold_c = _false_sd_rate(all_rows, best_margin)
    confusion: dict[str, dict[str, int]] = {l: {"S": 0, "D": 0, "C": 0} for l in "SDC"}
    for _t, gold, pred, m in all_rows:
        eff = pred if m >= best_margin else "C"
        confusion[gold][eff] += 1

    out = ROOT / "docs/research/router-calibration.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    lat_sorted = sorted(latencies)
    p50 = statistics.median(lat_sorted)
    p90 = lat_sorted[int(len(lat_sorted) * 0.9)] if lat_sorted else 0.0
    md = f"""# Router Tier 1 calibration

Generated by `scripts/calibrate_router.py` on {time.strftime("%Y-%m-%d %H:%M %Z")}.

## Setup

| Setting | Value |
|---|---|
| Embed model | `{cfg.embed_model}` |
| Ollama host | `{settings.ollama_host}` |
| Static examples | {len(static)} |
| Hold-out utterances | {len(holdout)} |
| LOO wall time | {loo_sec:.1f}s |

## Latency (warm index, query + NN)

| Percentile | ms |
|---|---|
| p50 | {p50:.1f} |
| p90 | {p90:.1f} |

Phrases probed: `summarise everything`, `make the button blue`, `stop speaking`.

## Threshold search

Target: false **S/D** on gold **C** utterances ≤ 3% when acting on margin.

| Suggested `ROUTER_T1_MARGIN` | {best_margin:.3f} |
|---|---|
| Accuracy (effective label) | {best_acc * 100:.1f}% |
| False S/D on gold C | {rate * 100:.2f}% ({wrong}/{gold_c}) |

## Confusion (effective label at margin ≥ {best_margin:.3f})

```
{json.dumps(confusion, indent=2)}
```

## Notes

- Tier 1 uses per-label max cosine similarity; confidence = margin to runner-up label.
- Static vectors cached under `data/router_t1_cache_*.json`.
- Tier 2 (qwen3:0.6b) is not part of this calibration run.
"""
    out.write_text(md, encoding="utf-8")
    print(f"Wrote {out}")
    print(f"Suggested ROUTER_T1_MARGIN={best_margin:.3f} acc={best_acc*100:.1f}% falseSD={rate*100:.2f}%")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())